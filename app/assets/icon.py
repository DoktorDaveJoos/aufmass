"""Writes icon.svg and icon-small.svg next to this script.

    python3 app/assets/icon.py <folder with Inter-SemiBold.ttf and Inter-Bold.ttf>

Needs fontTools. icon.ico (16 to 32 px from icon-small.svg, 48 to 256 px
from icon.svg) and icon-macos.png (icon.svg at 412 px on a 512 px canvas,
macOS's icon margin) are then rendered from the SVGs, e.g. with resvg.
"""
import math, os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
F=os.path.join(sys.argv[1], '')
OUT=os.path.join(os.path.dirname(os.path.abspath(__file__)), '')

def glyph(file):
    f=TTFont(F+file); gs=f.getGlyphSet(); p=SVGPathPen(gs); gs[f.getBestCmap()[65]].draw(p); return p.getCommands()

def squircle(size, inset=0, n=4.6, steps=256):
    # Superellipse, as Apple's continuous-corner icon shape.
    a=(size-2*inset)/2; c=size/2; pts=[]
    for i in range(steps):
        t=2*math.pi*i/steps; ct, st = math.cos(t), math.sin(t)
        x=c+a*math.copysign(abs(ct)**(2/n), ct); y=c+a*math.copysign(abs(st)**(2/n), st)
        pts.append(f'{x:.1f} {y:.1f}')
    return 'M'+' L'.join(pts)+'Z'

BG='''  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#0c0cd0"/>
      <stop offset=".55" stop-color="#0000bd"/>
      <stop offset="1" stop-color="#000094"/>
    </linearGradient>
    <radialGradient id="light" cx=".3" cy=".18" r=".8">
      <stop offset="0" stop-color="#fff" stop-opacity=".10"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </radialGradient>
    <pattern id="minor" width="32" height="32" patternUnits="userSpaceOnUse">
      <path d="M32 0H0V32" fill="none" stroke="#fff" stroke-opacity=".05" stroke-width="2"/>
    </pattern>
    <pattern id="major" width="128" height="128" patternUnits="userSpaceOnUse">
      <path d="M128 0H0V128" fill="none" stroke="#fff" stroke-opacity=".11" stroke-width="3"/>
    </pattern>
    <clipPath id="shape"><path d="{shape}"/></clipPath>
    <filter id="lift" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="10" stdDeviation="14" flood-color="#000040" flood-opacity=".45"/>
    </filter>
  </defs>
  <g clip-path="url(#shape)">
    <rect width="1024" height="1024" fill="url(#bg)"/>
    <rect width="1024" height="1024" fill="url(#minor)"/>
    <rect width="1024" height="1024" fill="url(#major)"/>
    <rect width="1024" height="1024" fill="url(#light)"/>
  </g>
  <path d="{edge}" fill="none" stroke="#fff" stroke-opacity=".12" stroke-width="4"/>
'''

def full():
    H=500; s=H/1490
    width=1391*s; Lx=512-(width+144)/2+24; By=697; Top=By-H
    X=lambda gx: Lx+(gx-50)*s; Y=lambda gy: By-gy*s
    Rx=X(1441); Dx=Rx+90; cx=X(745.5)
    tx=Lx-50*s
    def ext(p,q,d):  # line p->q extended by d at both ends
        (x1,y1),(x2,y2)=p,q; l=math.hypot(x2-x1,y2-y1); ux,uy=(x2-x1)/l,(y2-y1)/l
        return f'M{x1-ux*d:.1f} {y1-uy*d:.1f} {x2+ux*d:.1f} {y2+uy*d:.1f}'
    left=ext((X(50),Y(0)),(X(570),Y(1490)),70); right=ext((X(1441),Y(0)),(X(909),Y(1490)),70)
    grips=''.join(f'<rect x="{X(gx)-13:.1f}" y="{Y(gy)-13:.1f}" width="26" height="26"/>' for gx,gy in [(50,0),(1441,0),(570,1490),(909,1490)])
    tick=lambda x,y: f'M{x-18:.1f} {y+18:.1f} {x+18:.1f} {y-18:.1f}'
    wy=By+100
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- App icon: the A of Inter SemiBold (the brand font) drawn as a measured
       part on blueprint paper: construction lines, centre line, CAD grips and
       width and height dimensions. Brand blue #0000bd. Generated by icon.py. -->
{BG.format(shape=squircle(1024), edge=squircle(1024, 2))}  <g fill="none" stroke="#fff" stroke-linecap="round">
    <path d="{left}{right}" stroke-width="3" stroke-opacity=".35"/>
    <path d="M{cx:.1f} {Top-70:.1f}V{By+50:.1f}" stroke-width="4" stroke-opacity=".4" stroke-dasharray="44 14 6 14"/>
  </g>
  <path filter="url(#lift)" fill="#fff" transform="translate({tx:.2f} {By:.2f}) scale({s:.5f} {-s:.5f})" d="{glyph('Inter-SemiBold.ttf')}"/>
  <g fill="#0000bd" stroke="#fff" stroke-width="5">{grips}</g>
  <g fill="none" stroke="#fff" stroke-linecap="round" stroke-opacity=".85">
    <path d="M{X(50):.1f} {By+40}V{By+130}M{Rx:.1f} {By+40}V{By+130}M{X(50)-24:.1f} {wy}H{Rx+24:.1f}" stroke-width="8"/>
    <path d="M{X(909)+40:.1f} {Top:.1f}H{Dx+30:.1f}M{Rx+40:.1f} {By}H{Dx+30:.1f}M{Dx:.1f} {Top-24:.1f}V{By+24}" stroke-width="8"/>
    <path d="{tick(X(50),wy)}{tick(Rx,wy)}{tick(Dx,Top)}{tick(Dx,By)}" stroke-width="16" stroke-opacity="1"/>
  </g>
</svg>
'''

def small():
    H=640; s=H/1490; width=1391*s; Lx=512-width/2; By=832
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- icon.svg for 16 to 32 px: the same ground without the drawing details,
       a bolder, larger A. Generated by icon.py. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#0c0cd0"/>
      <stop offset="1" stop-color="#00009e"/>
    </linearGradient>
  </defs>
  <path d="{squircle(1024)}" fill="url(#bg)"/>
  <path fill="#fff" transform="translate({Lx-50*s:.2f} {By}) scale({s:.5f} {-s:.5f})" d="{glyph('Inter-Bold.ttf')}"/>
</svg>
'''
open(OUT+'icon.svg','w').write(full()); open(OUT+'icon-small.svg','w').write(small())
